const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { parse } = require('dotenv');
const { localSettings, EMAIL } = require('./local-settings');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'squirl-local-settings-'));
const Database = require('better-sqlite3-multiple-ciphers');
const db = new Database(':memory:');
require.cache[require.resolve('../src/config/db')] = { exports: { getDb: () => db } };
require.cache[require.resolve('../src/config')] = { exports: { push: {}, llm: { model: 'synthetic' } } };
const { seedLocal, samplePayment } = require('./local-fixtures');
const { verifyPassword } = require('../src/core/password');

async function main() {
  const original = 'DB_PATH=/not-a-real-home-db\nDB_KEY=synthetic-home-key\nPORT=9999\n';
  fs.writeFileSync(path.join(root, '.env'), original);
  const first = localSettings(root), second = localSettings(root);
  assert.equal(first.env.DB_KEY, second.env.DB_KEY, 'the dev key persists across launches');
  assert.equal(first.env.PUSH_PRIVATE_KEY, second.env.PUSH_PRIVATE_KEY);
  assert.match(first.password, /^demo-[\w-]{12}$/); assert.equal(first.password, second.password, 'the demo password persists');
  assert.equal(first.passwordAdded, false);
  assert.notEqual(first.env.DB_KEY, 'synthetic-home-key');
  assert.equal(fs.readFileSync(path.join(root, '.env'), 'utf8'), original);
  assert.equal(fs.statSync(first.env.DOTENV_CONFIG_PATH).mode & 0o777, 0o600);
  assert.equal(first.env.DB_PATH, path.join(root, '.local/squirl-dev.db'));
  assert.equal(first.env.REDIS_URL, 'redis://127.0.0.1:6381');
  const inherited = { ...process.env, DOTENV_CONFIG_PATH: first.env.DOTENV_CONFIG_PATH };
  for (const key of ['DB_PATH', 'DB_KEY', 'PORT', 'COOKIE_SECURE']) delete inherited[key];
  const selected = execFileSync(process.execPath, ['-e', `const c = require(${JSON.stringify(path.resolve(__dirname, '../src/config'))}); console.log(JSON.stringify({path:c.db.path,port:c.port,secure:c.session.cookieSecure}));`], { env: inherited, cwd: root, encoding: 'utf8' });
  assert.deepEqual(JSON.parse(selected.trim().split('\n').at(-1)), { path: first.database, port: 4000, secure: false }, 'only the selected env file is loaded');
  const file = first.env.DOTENV_CONFIG_PATH, content = fs.readFileSync(file, 'utf8');
  fs.writeFileSync(file, content.replace(JSON.stringify(first.database), '"/not-a-real-home-db"'));
  assert.throws(() => localSettings(root), /dedicated .local database/);
  fs.writeFileSync(file, content);
  fs.writeFileSync(first.database, 'synthetic placeholder, not a real database');
  fs.renameSync(file, `${file}.retained`);
  assert.throws(() => localSettings(root), /settings\/key are missing/);
  fs.renameSync(`${file}.retained`, file);
  fs.unlinkSync(first.database);
  fs.symlinkSync(path.join(root, '.env'), first.database);
  assert.throws(() => localSettings(root), /symbolic links/);
  fs.unlinkSync(first.database);
  fs.symlinkSync(path.join(root, 'missing.db'), first.database);
  assert.throws(() => localSettings(root), /symbolic links/, 'dangling links cannot redirect a new local database');
  fs.unlinkSync(first.database);
  fs.linkSync(path.join(root, '.env'), first.database);
  assert.throws(() => localSettings(root), /hard links/);
  fs.unlinkSync(first.database);

  for (const migration of require('../src/config/migrations')) typeof migration === 'function' ? migration(db) : db.exec(migration);
  db.pragma('foreign_keys = ON');
  assert.equal(await seedLocal(db, first.password), true);
  const user = db.prepare('SELECT * FROM users WHERE email = ?').get(EMAIL);
  assert(await verifyPassword(first.password, user.password_hash));
  // An older setup without a stored password gets one, and the demo login is moved to it.
  const envFile = first.env.DOTENV_CONFIG_PATH;
  fs.writeFileSync(envFile, fs.readFileSync(envFile, 'utf8').replace(/^LOCAL_DEMO_PASSWORD=.*\n/m, ''));
  const upgraded = localSettings(root);
  assert.equal(upgraded.passwordAdded, true); assert.notEqual(upgraded.password, first.password);
  await require('./local-fixtures').setDemoPassword(db, upgraded.password);
  assert(await verifyPassword(upgraded.password, db.prepare('SELECT password_hash FROM users WHERE email = ?').pluck().get(EMAIL)));
  const count = (table) => db.prepare(`SELECT count(*) FROM ${table}`).pluck().get();
  assert(count('transactions') >= 25); assert.equal(count('tasks'), 3); assert.equal(count('habits'), 2); assert.equal(count('goals'), 1);
  const tx = db.prepare('SELECT * FROM transactions ORDER BY rowid LIMIT 1').get();
  db.prepare('UPDATE transactions SET notes = ? WHERE id = ?').run('Keep my local edits', tx.id);
  const before = count('transactions');
  assert.equal(await seedLocal(db, first.password), false);
  assert.equal(count('transactions'), before);
  assert.equal(db.prepare('SELECT notes FROM transactions WHERE id = ?').pluck().get(tx.id), 'Keep my local edits');
  const id = samplePayment(db, user.id);
  assert.equal(count('transactions'), before + 1);
  assert(db.prepare('SELECT id FROM payment_prompts WHERE transaction_id = ?').get(id));
  assert.equal(db.pragma('foreign_key_check').length, 0);
  console.log('Passed: separate env/key/Redis, untouched home settings, selected config, path/key/link guards, real password hashing, fixture seeding, preserved edits, and sample payment prompts.');
}
main().catch((error) => { console.error(error); process.exitCode = 1; }).finally(() => { db.close(); fs.rmSync(root, { recursive: true, force: true }); });
